"""
Pydantic Schemas for Incident Triage.
Defines strict types and validation for AI classification outputs.
"""

from enum import Enum
from typing import Optional
from datetime import datetime, timezone
from pydantic import BaseModel, Field, field_validator, model_validator


class IncidentType(str, Enum):
    MEDICAL = "MEDICAL"
    HARASSMENT = "HARASSMENT"
    VIOLENCE = "VIOLENCE"
    ACCIDENT = "ACCIDENT"
    FIRE = "FIRE"
    OTHER = "OTHER"


class TriageRequest(BaseModel):
    """Input payload for AI triage."""
    incident_id: Optional[str] = Field(None, description="Optional incident identifier if already generated")
    description: str = Field(..., min_length=1, description="Citizen report or transcript in Kannada, Hindi, or English")
    language_hint: Optional[str] = Field(None, description="Optional language hint: kn, hi, en, etc.")
    latitude: Optional[float] = Field(None, ge=-90.0, le=90.0)
    longitude: Optional[float] = Field(None, ge=-180.0, le=180.0)


class TriageResult(BaseModel):
    """
    Validated structured triage data.
    Strictly conforms to required specification:
    - incident_type: MEDICAL, HARASSMENT, VIOLENCE, ACCIDENT, FIRE or OTHER
    - severity: integer 1–5
    - confidence: number between 0 and 1
    - possible_duplicate: boolean
    - spam_flag: boolean
    - reason: short explanation
    """
    incident_type: IncidentType = Field(..., description="Classified incident category")
    severity: int = Field(..., ge=1, le=5, description="Incident severity level from 1 (minor) to 5 (critical/life-threatening)")
    confidence: float = Field(..., ge=0.0, le=1.0, description="Model classification confidence between 0.0 and 1.0")
    possible_duplicate: bool = Field(False, description="Flag indicating this report might be a duplicate candidate")
    spam_flag: bool = Field(False, description="Advisory flag indicating suspected spam or frivolous report")
    reason: str = Field(..., max_length=500, description="Short factual explanation for the classification")

    # Safety, disclaimer, and audit metadata
    is_fallback: bool = Field(False, description="True if classification was generated by safe fallback due to AI error/timeout")
    triage_error: Optional[str] = Field(None, description="Error details if fallback was triggered")
    detected_language: Optional[str] = Field(None, description="Detected source language (e.g., kn, hi, en)")
    medical_disclaimer: str = Field(
        default="AI severity is an advisory prioritization score and NOT a certified medical assessment.",
        description="Mandatory disclaimer for health-related categorizations"
    )
    triaged_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

    @field_validator("incident_type", mode="before")
    @classmethod
    def normalize_incident_type(cls, v: str) -> IncidentType:
        if isinstance(v, str):
            v_upper = v.strip().upper()
            if v_upper in IncidentType.__members__:
                return IncidentType[v_upper]
        elif isinstance(v, IncidentType):
            return v
        raise ValueError(f"Invalid incident_type '{v}'. Must be one of: {list(IncidentType.__members__.keys())}")

    @field_validator("severity", mode="before")
    @classmethod
    def validate_severity(cls, v) -> int:
        try:
            val = int(v)
        except (ValueError, TypeError):
            raise ValueError(f"Severity must be an integer, got {v}")
        if not (1 <= val <= 5):
            raise ValueError(f"Severity must be between 1 and 5, got {val}")
        return val

    @field_validator("confidence", mode="before")
    @classmethod
    def validate_confidence(cls, v) -> float:
        try:
            val = float(v)
        except (ValueError, TypeError):
            raise ValueError(f"Confidence must be a numeric float, got {v}")
        if not (0.0 <= val <= 1.0):
            raise ValueError(f"Confidence must be between 0.0 and 1.0, got {val}")
        return round(val, 4)
